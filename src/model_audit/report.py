"""Markdown audit report generated from check results."""

from __future__ import annotations

import os
from pathlib import Path

import pandas as pd

from .pipeline import AuditOutput
from .status import Status
from .summary import traffic_light

RISK = {Status.FAIL: "High", Status.WATCH: "Medium"}
RAG_WORD = {Status.PASS: "Green", Status.WATCH: "Amber", Status.FAIL: "Red"}


def _fmt(v):
    if isinstance(v, float):
        if v == int(v):
            return str(int(v))
        return f"{v:.4g}" if abs(v) < 1 else f"{v:,.2f}"
    return str(v)


def md_table(df: pd.DataFrame, pct_cols=(), sci_cols=("p_value", "p_holm"), digits=3) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    data = {c: df[c].tolist() for c in cols}  # column-wise keeps int columns as ints
    for i in range(len(df)):
        cells = []
        for c in cols:
            v = data[c][i]
            if c in pct_cols and isinstance(v, float):
                cells.append(f"{v:.1%}")
            elif c in sci_cols and isinstance(v, float):
                cells.append(f"{v:.2g}")
            elif isinstance(v, float):
                cells.append(f"{v:.{digits}f}")
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _rel(path: Path, start: Path) -> str:
    return os.path.relpath(path, start).replace(os.sep, "/")


def _esc(s: str) -> str:
    return s.replace("|", "\\|")


def build_report(out: AuditOutput, cfg: dict, fig_paths: list[Path], report_path: Path) -> str:
    m, res = out.meta, out.results
    counts = {s: sum(r.status == s for r in res) for s in Status}
    L: list[str] = []
    L += [
        "# Credit model audit report",
        "",
        "_Generated by `model-audit`. Subject: a reference WoE scorecard built in this "
        "repository on a public dataset, audited against a simulated monitoring sample. "
        "This is a demonstration, not an assessment of any production model._",
        "",
    ]
    L += [
        "## 1. Scope and set-up",
        "",
        f"- Development sample: {m['n_dev']:,} accounts, observed default rate {m['dr_dev']:.2%}, "
        f"mean predicted PD {m['pd_dev']:.2%}.",
        f"- Monitoring sample: {m['n_mon']:,} rows (after injected duplicates), observed default "
        f"rate {m['dr_mon']:.2%}, mean predicted PD {m['pd_mon']:.2%}.",
        f"- Score scale: {m['base_score']} points at {m['base_odds']}:1 good:bad odds, "
        f"PDO {m['pdo']}; random seed {m['seed']}.",
        f"- Scorecard: {m['binning']} binning, characteristics {', '.join(m['coef'])}"
        + (f"; dropped for a wrong-sign coefficient: {', '.join(m['dropped'])}" if m["dropped"] else "")
        + (f"; zeroed by the L1 penalty: {', '.join(m['zeroed'])}" if m["zeroed"] else "")
        + (
            f"; regularisation tuned by 5-fold CV: C = {m['tuning']['C']:.3g}, "
            f"L1 share {m['tuning']['l1_ratio']:g}."
            if m["tuning"]
            else "."
        ),
        "- Status rule: Pass / Watch / Fail against the thresholds shown per check; the "
        "thresholds are conventions and must be aligned with the institution's policy.",
        "",
    ]
    if out.notes:
        L += ["### Simulated drift (ground truth injected into the monitoring sample)", ""]
        L += [f"- {n}" for n in out.notes] + [""]

    L += [
        "## 2. Summary",
        "",
        f"**{counts[Status.FAIL]} Fail, {counts[Status.WATCH]} Watch, "
        f"{counts[Status.PASS]} Pass** out of {len(res)} checks.",
        "",
    ]
    tl, overall = traffic_light(res)
    L += [
        f"Overall rating: {RAG_WORD[overall]} (worst area; see rule in section 5).",
        "",
        md_table(tl.rename(columns=str.capitalize)),
        "",
    ]
    if "traffic_light" in {p.stem for p in fig_paths}:
        tlp = next(p for p in fig_paths if p.stem == "traffic_light")
        L += [f"![Traffic light]({_rel(tlp, report_path.parent)})", ""]
    rows = [
        {
            "ID": r.check_id,
            "Check": r.name,
            "Metric": r.metric,
            "Value": _fmt(r.value),
            "Threshold": r.threshold,
            "Status": r.status.label,
        }
        for r in res
    ]
    L += [md_table(pd.DataFrame(rows)), ""]

    L += [
        "## 3. Findings",
        "",
        "Raised for every check that is not Pass. Risk rating: Fail = High, Watch = Medium.",
        "",
    ]
    ordered = sorted((r for r in res if r.status != Status.PASS), key=lambda r: -r.status)
    if ordered:
        L += ["| # | Ref | Observation | Risk | Recommendation |", "|---|---|---|---|---|"]
        for i, r in enumerate(ordered, 1):
            L.append(
                f"| {i} | {r.check_id} {r.name} | {_esc(r.observation)} | "
                f"{RISK[r.status]} | {_esc(r.recommendation)} |"
            )
    else:
        L.append("No exceptions.")
    L.append("")
    passed = [r for r in res if r.status == Status.PASS]
    if passed:
        L += ["### Tests without exception", ""]
        L += [f"- {r.check_id} {r.name}: {r.observation}" for r in passed] + [""]

    L += ["## 4. Supporting evidence", ""]
    names = {p.stem: p for p in fig_paths}
    if "psi_bars" in names:
        L += [f"![PSI and CSI]({_rel(names['psi_bars'], report_path.parent)})", ""]
    L += ["### Stability", "", md_table(out.tables["csi"], digits=3), ""]
    if "roc_ks" in names:
        L += [f"![ROC and KS]({_rel(names['roc_ks'], report_path.parent)})", ""]
    d = out.tables["discrimination"].copy()
    d["95% CI"] = d.apply(lambda r: f"{r.ci_low:.3f} to {r.ci_high:.3f}", axis=1)
    L += ["### Discrimination", "", md_table(d[["metric", "sample", "value", "95% CI"]]), ""]
    if "calibration" in names:
        L += [f"![Calibration]({_rel(names['calibration'], report_path.parent)})", ""]
    L += [
        "### Calibration by score band (monitoring)",
        "",
        md_table(out.tables["calibration_bands"], pct_cols=("mean_pd", "observed_dr", "ci_low", "ci_high")),
        "",
    ]
    gt = next(r for r in res if r.check_id == "CA-02").details["table"]
    L += [
        "### Binomial test by rating grade (monitoring)",
        "",
        md_table(gt, pct_cols=("grade_pd", "observed_dr")),
        "",
    ]
    jt = next(r for r in res if r.check_id == "CA-05").details["table"]
    L += [
        "### Jeffreys test by rating grade (monitoring)",
        "",
        md_table(jt, pct_cols=("grade_pd",)),
        "",
    ]
    L += [
        "### Rating grades",
        "",
        md_table(out.tables["grades"], pct_cols=("dev_share", "mon_share", "dev_dr", "mon_dr")),
        "",
    ]
    if "overrides" in out.tables:
        L += [
            "### Overrides",
            "",
            md_table(out.tables["overrides"], pct_cols=("default_rate", "mean_pd")),
            "",
        ]
    if "benchmark" in out.tables:
        L += [
            "### Champion vs challenger",
            "",
            md_table(out.tables["benchmark"], pct_cols=("mean_pd",)),
            "",
            md_table(out.tables["challenger_cv"], digits=3),
            "",
            "Challenger hyper-parameters (Optuna, TPE, 5-fold CV log loss):",
            "",
            md_table(out.tables["challenger_params"], digits=4),
            "",
        ]
    L += [
        "### Data quality",
        "",
        md_table(out.tables["missing"], pct_cols=("dev_missing", "mon_missing")),
        "",
        md_table(out.tables["ranges"], pct_cols=("share",)),
        "",
    ]
    L += [
        "## 5. Method notes",
        "",
        "- Every metric is re-computed from record-level data with the library code in "
        "`src/model_audit`; nothing is taken from model documentation.",
        "- PD: cubic logistic recalibration of default on the standardised score, fitted on the "
        "development sample, frozen and applied to monitoring (calibrate_pd = false falls back to "
        "the points-scale PD, logit(PD) = (offset - score) / factor).",
        "- Bootstrap CIs: percentile method, resampling accounts with replacement.",
        "- Hosmer-Lemeshow on monitoring uses groups degrees of freedom (frozen model).",
        "- Traffic light: an area is Red if any of its checks Fails, Amber if any is Watch, "
        "otherwise Green. The overall rating is the worst area.",
        "- Large samples make formal tests reject small deviations: read p-values with the effect sizes.",
        "",
    ]
    text = "\n".join(L)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(text)
    return text
